return function(T)
  T.suite("normalize")
  local pii = require("pii")
  pii.load(T.opts.rules)

  T.case("MY NRIC: only the exact 6-2-4 hyphen layout is stripped", function()
    local v, tr = pii.normalize("MY.nric", "900101-01-0001")
    T.eq(v, "900101010001", "stripped")
    T.eq(tr[1], "strip_fixed_separators", "transform recorded")
    v, tr = pii.normalize("MY.nric", "9001-0101-0001")
    T.eq(v, "9001-0101-0001", "wrong positions untouched")
    T.eq(#tr, 0, "no transform")
    v = pii.normalize("MY.nric", "900101010001")
    T.eq(v, "900101010001", "plain untouched")
    v = pii.normalize("MY.nric", "900101-01-0001-")
    T.eq(v, "900101-01-0001-", "extra separator untouched")
  end)

  T.case("HKID: only a single trailing (x) pair is removed", function()
    T.eq((pii.normalize("HK.hkid", "A123456(3)")), "A1234563", "parens stripped")
    T.eq((pii.normalize("HK.hkid", "A123456(A)")), "A123456A", "letter check")
    T.eq((pii.normalize("HK.hkid", "A123456(33)")), "A123456(33)", "two chars inside untouched")
    T.eq((pii.normalize("HK.hkid", "(A)123456")), "(A)123456", "leading parens untouched")
    T.eq((pii.normalize("HK.hkid", "A123456 3")), "A123456 3", "space untouched")
  end)

  T.case("IBAN: print-format spaces only in 4-groups; no generic whitespace removal", function()
    T.eq((pii.normalize("AE.iban", "AE15 1111 1111 1111 1111 111")), "AE151111111111111111111", "4-groups")
    T.eq((pii.normalize("AE.iban", "AE15  1111 1111 1111 1111 111")), "AE15  1111 1111 1111 1111 111", "double space untouched")
    T.eq((pii.normalize("AE.iban", " AE151111111111111111111")), " AE151111111111111111111", "leading space untouched")
    T.eq((pii.normalize("AE.iban", "AE1 51111 1111")), "AE1 51111 1111", "irregular groups untouched")
    T.eq((pii.normalize("AE.iban", "AE151111111111111111111\t")), "AE151111111111111111111\t", "tab untouched")
  end)

  T.case("SG foreign company: three spaces -> 000 only in the exact legacy layout", function()
    T.eq((pii.normalize("SG.foreign_company_tax_ref", "F   12345A")), "F00012345A", "legacy layout")
    T.eq((pii.normalize("SG.foreign_company_tax_ref", "F  12345A")), "F  12345A", "two spaces untouched")
    T.eq((pii.normalize("SG.foreign_company_tax_ref", "F 000 12345A")), "F 000 12345A", "other spacing untouched")
  end)

  T.case("ASCII upper-casing happens only with the explicit option; never NFKC", function()
    local v, tr = pii.normalize("CN.uscc", "91110101abcdefgh1e")
    T.eq(v, "91110101abcdefgh1e", "no option: unchanged")
    T.eq(#tr, 0, "no transform")
    v, tr = pii.normalize("CN.uscc", "91110101abcdefgh1e", { ascii_uppercase = true })
    T.eq(v, "91110101ABCDEFGH1E", "upper-cased")
    T.eq(tr[1], "ascii_uppercase", "recorded")
    v = pii.normalize("CN.resident_id", "11010519491231002x", { ascii_uppercase = true })
    T.eq(v, "11010519491231002X", "trailing x only")
    v = pii.normalize("CN.resident_id", "1101051949123100x2", { ascii_uppercase = true })
    T.eq(v, "1101051949123100x2", "x elsewhere untouched (regex will reject)")
    v = pii.normalize("CN.uscc", "９1110101ABCDEFGH1E", { ascii_uppercase = true })
    T.eq(v, "９1110101ABCDEFGH1E", "full-width digit not folded")
  end)

  T.case("rules without normalization entries return the value verbatim", function()
    local v, tr = pii.normalize("TH.citizen_id", " 1234567890121 ", { ascii_uppercase = true })
    T.eq(v, " 1234567890121 ", "verbatim")
    T.eq(#tr, 0, "no transforms")
  end)

  T.case("validate() never normalizes implicitly", function()
    local r = pii.validate("MY.nric", "900101-01-0001")
    T.eq(r.syntax, "fail", "hyphenated input fails without normalize option")
    r = pii.validate("MY.nric", "900101-01-0001", { normalize = true })
    T.eq(r.syntax, "pass", "passes with explicit normalize")
    T.eq(r.normalized_value, "900101010001", "normalized value reported")
    T.eq(r.transformations[1], "strip_fixed_separators", "transform reported")
  end)
end
