return function(T)
  T.suite("semantic")
  local sem = require("pii.semantic")
  local pii = require("pii")
  pii.load(T.opts.rules)

  T.case("leap year rules: 1900 no, 2000 yes, 2024 yes, 2100 no", function()
    T.eq(sem.is_leap(1900), false, "1900")
    T.eq(sem.is_leap(2000), true, "2000")
    T.eq(sem.is_leap(2024), true, "2024")
    T.eq(sem.is_leap(2100), false, "2100")
    T.eq(sem.is_leap(2023), false, "2023")
  end)

  T.case("valid_date boundaries", function()
    T.eq(sem.valid_date(1990, 2, 30), false, "Feb 30")
    T.eq(sem.valid_date(1990, 0, 1), false, "month 0")
    T.eq(sem.valid_date(1990, 13, 1), false, "month 13")
    T.eq(sem.valid_date(1990, 1, 0), false, "day 0")
    T.eq(sem.valid_date(1990, 4, 31), false, "Apr 31")
    T.eq(sem.valid_date(1990, 12, 31), true, "Dec 31")
    T.eq(sem.valid_date(2000, 2, 29), true, "2000-02-29")
    T.eq(sem.valid_date(1900, 2, 29), false, "1900-02-29")
  end)

  T.case("parse_iso_date", function()
    local y, m, d = sem.parse_iso_date("2026-11-13")
    T.eq(y, 2026, "y"); T.eq(m, 11, "m"); T.eq(d, 13, "d")
    T.eq(sem.parse_iso_date("2026-02-30"), nil, "invalid")
    T.eq(sem.parse_iso_date("20261113"), nil, "format")
    T.eq(sem.parse_iso_date(nil), nil, "nil")
  end)

  T.case("CN: date validity, future check with reference date, region unknown", function()
    local r = pii.validate("CN.resident_id", "11010519900230001X")
    T.eq(r.semantic, "fail", "Feb 30 fails")
    T.eq(r.semantic_details.birth_date_gregorian, "fail", "detail")
    T.eq(r.semantic_details.region_code, "unknown", "region unknown")
    r = pii.validate("CN.resident_id", "110105209901010012", { reference_date = "2026-11-13" })
    T.eq(r.semantic, "fail", "future date fails with reference")
    T.eq(r.semantic_details.not_after_reference_date, "fail", "detail")
    r = pii.validate("CN.resident_id", "110105209901010012")
    T.eq(r.semantic, "pass", "no reference date: not checked")
    T.eq(r.semantic_details.not_after_reference_date, nil, "no detail")
    r = pii.validate("CN.resident_id", "110105209901010012", { reference_date = "garbage" })
    T.eq(r.semantic_details.not_after_reference_date, nil, "unparseable reference ignored")
  end)

  T.case("ID NIK: female +40, invalid days, ambiguous century", function()
    local r = pii.validate("ID.nik", "3273014101900002")
    T.eq(r.semantic, "pass", "day 41 -> 1 female")
    T.eq(r.semantic_details.sex_encoding, "female_day_plus_40", "sex detail")
    T.eq(r.semantic_details.century, "unknown", "century unknown")
    T.eq(pii.validate("ID.nik", "3273017101900002").semantic, "pass", "day 71 -> 31 Jan")
    T.eq(pii.validate("ID.nik", "3273017102900002").semantic, "fail", "day 71 -> 31 Feb invalid")
    T.eq(pii.validate("ID.nik", "3273010001900002").semantic, "fail", "day 00")
    T.eq(pii.validate("ID.nik", "3273010113900002").semantic, "fail", "month 13")
    T.eq(pii.validate("ID.nik", "3273012902000002").semantic, "pass", "29 Feb yy=00 (2000 leap)")
    T.eq(pii.validate("ID.nik", "3273012902010002").semantic, "fail", "29 Feb yy=01 never leap")
  end)

  T.case("MY NRIC: YYMMDD plausibility, century and birthplace unknown", function()
    local r = pii.validate("MY.nric", "000229010001")
    T.eq(r.semantic, "pass", "00-02-29 plausible via 2000")
    T.eq(r.semantic_details.birthplace_code, "unknown", "birthplace unknown")
    T.eq(pii.validate("MY.nric", "010229010001").semantic, "fail", "01-02-29 impossible")
    T.eq(pii.validate("MY.nric", "901301010001").semantic, "fail", "month 13")
  end)

  T.case("KR RRN: century digit mapping and date validity", function()
    local opt = { kr_rrn_regime = "current_post_2020_10" }
    T.eq(pii.validate("KR.rrn", "0002293000000", opt).semantic, "pass", "3 -> 2000-02-29")
    T.eq(pii.validate("KR.rrn", "0002291000000", opt).semantic, "fail", "1 -> 1900-02-29 invalid")
    T.eq(pii.validate("KR.rrn", "0002299000000", opt).semantic, "fail", "9 -> 1800-02-29 invalid")
    T.eq(pii.validate("KR.rrn", "9613012000000", opt).semantic, "fail", "month 13")
    T.eq(pii.validate("KR.rrn", "9912312000000", opt).semantic, "pass", "1999-12-31")
    local r = pii.validate("KR.rrn", "9912313000000", { kr_rrn_regime = "current_post_2020_10", reference_date = "2026-11-13" })
    T.eq(r.semantic, "fail", "2099-12-31 is in the future")
  end)

  T.case("IN PAN serial 0000 and IR repeated digits", function()
    T.eq(pii.validate("IN.pan", "ZZZPZ0000A").semantic, "fail", "serial 0000")
    T.eq(pii.validate("IN.pan", "ZZZPZ0001A").semantic, "pass", "serial 0001")
    T.eq(pii.validate("IR.national_code", "1111111111").semantic, "fail", "repeated")
    T.eq(pii.validate("IR.national_code", "0012345679").semantic, "pass", "not repeated")
    T.eq(pii.validate("IR.national_code", "1111111111", { ir_reject_repeated_digits = false }).semantic, "unknown", "policy off -> unknown")
  end)

  T.case("rules without semantic checks report not_applicable; semantic=false skips", function()
    T.eq(pii.validate("TH.citizen_id", "1234567890121").semantic, "not_applicable", "no checks listed")
    T.eq(pii.validate("CN.resident_id", "11010519491231002X", { semantic = false }).semantic, "not_evaluated", "skipped")
  end)
end
