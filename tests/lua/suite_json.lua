return function(T)
  T.suite("json")
  local json = require("pii.json")

  T.case("decode scalars, arrays, objects, escapes", function()
    local v = json.decode('{"a":[1,2.5,-3,true,false,null],"b":"x\\n\\u0041\\u00e9\\ud83d\\ude00","c":{}}')
    T.eq(v.a[1], 1, "int")
    T.eq(v.a[2], 2.5, "float")
    T.eq(v.a[3], -3, "neg")
    T.eq(v.a[4], true, "true")
    T.eq(v.a[5], false, "false")
    T.eq(v.a[6], json.null, "null")
    T.eq(v.b, "x\nA\195\169\240\159\152\128", "escapes incl. surrogate pair")
    T.eq(next(v.c), nil, "empty object")
  end)

  T.case("decode preserves leading zeros in strings and rejects trailing garbage", function()
    T.eq(json.decode('["0012345679"]')[1], "0012345679", "string kept verbatim")
    local ok = pcall(json.decode, '{"a":1} x')
    T.eq(ok, false, "trailing garbage raises")
    ok = pcall(json.decode, '{"a":}')
    T.eq(ok, false, "malformed raises")
  end)

  T.case("encode is deterministic and round-trips", function()
    local s = json.encode({ b = { 1, 2, 3 }, a = "q\"\\\n", n = 10, t = true, e = json.array({}) })
    T.eq(s, '{"a":"q\\"\\\\\\n","b":[1,2,3],"e":[],"n":10,"t":true}', "sorted keys, escapes, empty array")
    local back = json.decode(s)
    T.eq(back.a, "q\"\\\n", "roundtrip string")
    T.eq(back.b[3], 3, "roundtrip array")
    T.eq(json.encode(10.0), "10", "integral float printed as integer on every Lua version")
  end)

  T.case("decode_file loads a rules file", function()
    local doc = json.decode_file(T.opts.rules .. "/CN.json")
    T.eq(doc.jurisdiction, "CN", "jurisdiction")
    T.check(#doc.rules >= 4, "CN has at least 4 rules")
  end)
end
